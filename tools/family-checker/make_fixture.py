"""Builds fixtures/recorded-rpc.json, the recorded chain answers of the family checker's offline mode (MIT).

  python3 make_fixture.py            # write the fixture
  python3 make_fixture.py --check    # exit 1 unless the committed fixture equals the generated bytes

No network. Two kinds of entries, each marked in the fixture:

  recorded   real BNB Smart Chain reads already in this repository, re-encoded as the JSON-RPC answers the
             checker would receive: assets/tap-draft-design-credits/chain-reads.json (block 128,542,889: factory,
             processors, receipts, headers of four circuits) and assets/tap-draft-netlist-bound-nft/chain-snapshot.json
             (block 128,200,681: circuits, PoD miner records, mining parameters and tasks). The publication-fact
             reads come from the credits vectors (`publication.facts[*].reads`, the same chain-reads.json).
  synthetic  contracts that do not exist on any chain, answering as the reference contracts would for the
             vectors: the eight-token worked example as an L1 collection on chain 196 (its manifest hash, master
             seed, pools, hashes and entry indices come from vectors.json), a mint-bound contract, a plain L0
             contract with a freeze probe, a bridged copy, and the soulbound reference contract after the
             vectors' scenario (chain 31337, `final token states`). ERC-1271 answers and the container table are
             the credits vectors' recorded ones (`display.recorded`, `display.containers`).

Request keys are `<method>:<params as compact sorted JSON>`, the form chain.Rpc uses offline.
"""
