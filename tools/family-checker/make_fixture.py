def key(method: str, params) -> str:
    return method + ":" + json.dumps(params, sort_keys=True, separators=(",", ":"))


class Chain:
    def __init__(self, chain_id: int):
        self.id = chain_id
        self.req = {}
        self.notes = []

    def put(self, method, params, result):
        self.req[key(method, params)] = result

    def call(self, to, sig, args, block, result):
        self.put("eth_call", [{"to": to.lower(), "data": C.encode_call(sig, *args)}, hex(block)], result)

    def revert(self, to, sig, args, block, why="execution reverted"):
        self.call(to, sig, args, block, {"error": {"code": 3, "message": why}})


def words(*pairs) -> str:
    return C.encode_words(*pairs)


def enc_bool(v) -> str:
    return words(("bool", v))


def enc_uint(v) -> str:
    return words(("uint256", int(v)))


def enc_multi(types: list, values: list) -> str:
    """Multiple return values of static types and `string`s (no leading offset, as Solidity returns them)."""
    out, tail_off = b"", 32 * len(types)
    tail_chunks = []
    for t, v in zip(types, values):
        if t == "string":
            raw = v.encode()
            chunk = len(raw).to_bytes(32, "big") + raw + b"\0" * ((-len(raw)) % 32)
            out += tail_off.to_bytes(32, "big")
            tail_chunks.append(chunk)
            tail_off += len(chunk)
        else:
            out += C._word_of(t, v)
    return "0x" + (out + b"".join(tail_chunks)).hex()


def enc_pools(pools: list) -> str:
    """Pool[] of (string label, uint8 fields, bytes32 root): one dynamic array of dynamic tuples."""
    elems = []
    for label, mask, root in pools:
        raw = label.encode()
        tup = (96).to_bytes(32, "big") + C._word_of("uint8", mask) + C._word_of("bytes32", root)
        tup += len(raw).to_bytes(32, "big") + raw + b"\0" * ((-len(raw)) % 32)
        elems.append(tup)
    body = len(elems).to_bytes(32, "big")
    off = 32 * len(elems)
    for e in elems:
        body += off.to_bytes(32, "big")
        off += len(e)
    body += b"".join(elems)
    return "0x" + ((32).to_bytes(32, "big") + body).hex()


def interfaces(ch: Chain, addr: str, yes: set, block: int) -> None:
    for name, iid in tapfam.IID.items():
        ch.call(addr, "supportsInterface(bytes4)", (iid,), block, enc_bool(name in yes))


# ---------------------------------------------------------------- chain 56: recorded reads

def chain_56() -> Chain:
    ch = Chain(56)
    pinned = READS["pinnedBlock"]["number"]
    ch.notes.append(f"recorded: chain-reads.json at block {pinned} (finalized), chain-snapshot.json at block {SNAP['block']}")
    ch.put("eth_getBlockByNumber", ["finalized", False],
           {"number": hex(pinned), "hash": READS["pinnedBlock"]["hash"], "timestamp": hex(READS["pinnedBlock"]["timestamp"])})
    factory = READS["factory"]["address"]
    first = READS["stateNodes"][0]
    for c in READS["circuits"]:
        proc, cid = c["processor"], c["circuitId"]
        ch.call(factory, "isCPU(address)", (proc,), pinned, enc_bool(all(c["isCPU"].values())))
        ch.call(factory, "cpuAt(uint256)", (c["processorNumber"],), pinned, words(("address", c["cpuAt"][first])))
        ch.call(proc, "circuitInfo(uint256)", (cid,), pinned, c["circuitInfo"][first])
        ch.call(proc, "netlist(uint256)", (cid,), pinned, C.encode_bytes_return(bytes.fromhex(c["netlist"][first][2:])))
        ch.put("eth_getTransactionReceipt", [c["txHash"].lower()], c["receipt"][READS["nodes"][0]])
        hdr = c["block"][READS["nodes"][0]]
        ch.put("eth_getBlockByNumber", [hdr["number"], False], hdr)
        pub = c["receipt"][READS["nodes"][0]]["logs"]
        pub = next(l for l in pub if l["address"] == proc and l["topics"][0] == P.credits.TRANSFER_TOPIC)["topics"][2]
        ch.put("eth_getCode", ["0x" + pub[-40:], hex(pinned)], c["publisherCodeAtPinnedBlock"][first])
    B = SNAP["block"]
    mining = SNAP["mining"]["address"].lower()
    ch.call(mining, "lambda()", (), B, enc_uint(SNAP["mining"]["lambda"]))
    ch.call(mining, "beta()", (), B, enc_uint(SNAP["mining"]["beta"]))
    ch.call(mining, "lambdaBurn()", (), B, enc_uint(SNAP["mining"]["lambdaBurn"]))
    for p, m in SNAP["mining"]["processorMultiplier"].items():
        ch.call(mining, "processorMultiplier(address)", (p.lower(),), B, enc_uint(m))
    miner_types = tapfam.MINER_TYPES.split(",")
    for c in SNAP["circuits"]:
        proc, cid = c["processor"].lower(), c["circuitId"]
        ch.call(proc, "circuitInfo(uint256)", (cid,), B, words(("uint256", c["nIn"]), ("uint256", c["nOut"]), ("uint256", c["nState"]), ("uint256", c["gateCount"])))
        ch.call(proc, "netlist(uint256)", (cid,), B, C.encode_bytes_return(bytes.fromhex(c["netlist"][2:])))
        if c.get("miner"):
            ch.call(mining, "minerKey(address,uint256)", (proc, cid), B, words(("bytes32", c["minerKey"])))
            vals = []
            for t, f in zip(miner_types, tapfam.MINER_FIELDS):
                v = c["miner"][f]
                vals.append((t, v.lower() if t == "address" else (v == "true") if t == "bool" else int(v)))
            ch.call(mining, "getMiner(bytes32)", (c["minerKey"],), B, words(*vals))
            t = c.get("task")
            if t is None:
                continue
            ch.call(mining, "getTask(uint32)", (int(c["miner"]["taskId"]),), B, enc_multi(
                tapfam.TASK_TYPES, [int(t["kind"]), int(t["cycles"]), int(t["nIn"]), int(t["nOut"]), int(t["vectorCount"]), t["active"] == "true",
                                    t["vectorsRoot"], t["name"], int(t["refArea"]), int(t["refCost"]), t["refCircuits"].lower(), int(t["refCircuitId"])]))
        else:
            ch.call(mining, "minerKey(address,uint256)", (proc, cid), B, words(("bytes32", c.get("minerKey", ZERO32))))
    return ch


def publication_reads() -> dict:
    out = {}
    first = READS["stateNodes"][0]
    by_label = {c["label"]: c for c in READS["circuits"]}
    for x in VCR["publication"]["facts"]:
        f, reads = x["fact"], json.loads(json.dumps(x["reads"]))
        c = by_label[x["label"]]
        reads["netlist"] = c["netlist"]
        reads["publisherCode"] = c["publisherCodeAtPinnedBlock"]
        out[f"{f['chainId']}:{f['processor']}:{f['circuitId']}"] = reads
    return out


# ---------------------------------------------------------------- chain 196: the worked example as synthetic contracts

def chain_196() -> Chain:
    ch = Chain(196)
    ch.notes.append("synthetic: no contract at these addresses exists on X Layer; the answers are what the reference contracts return for the vectors")
    ch.put("eth_getBlockByNumber", ["safe", False], {"number": hex(XL_BLOCK)})
    B = XL_BLOCK
    ex = V721["example"]
    man = json.loads(ex["manifestText"])
    for addr in (EXAMPLE, MINT_BOUND, L0_FREEZE, MIRROR):
        ch.put("eth_getCode", [addr, hex(B)], "0xfe")
    # the worked example: an L1 collection, revealed and frozen
    interfaces(ch, EXAMPLE, {"ERC165", "ERC721", "ERC4906", "ITapNetlistNFT"}, B)
    ch.call(EXAMPLE, "collection()", (), B, words(("address", EXAMPLE)))
    ch.call(EXAMPLE, "tokenRange()", (), B, words(("uint256", ex["collection"]["firstTokenId"]), ("uint256", ex["collection"]["supply"])))
    ch.call(EXAMPLE, "manifestHash()", (), B, words(("bytes32", ex["manifestSha256"])))
    ch.call(EXAMPLE, "masterSeed()", (), B, words(("bytes32", ex["masterSeed"])))
    ch.call(EXAMPLE, "pools()", (), B, enc_pools([(p["label"], P.tapnft.fields_mask(p["fields"]), p["root"]) for p in man["pools"]]))
    ch.call(EXAMPLE, "frozen()", (), B, enc_bool(True))
    ch.call(EXAMPLE, "uriFrozen()", (), B, enc_bool(True))
    for t in ex["tokens"]:
        tid = t["tokenId"]
        ch.call(EXAMPLE, "netlistHashOf(uint256)", (tid,), B, words(("bytes32", t["netlistHash"])))
        ch.call(EXAMPLE, "imageHashOf(uint256)", (tid,), B, words(("bytes32", t["imageHash"])))
        ch.call(EXAMPLE, "entryIndexOf(uint256,uint256)", (tid, 0), B, enc_uint(t["imageEntry"]))
        ch.call(EXAMPLE, "entryIndexOf(uint256,uint256)", (tid, 1), B, enc_uint(t["netlistEntry"]))
        ch.call(EXAMPLE, "tokenURI(uint256)", (tid,), B, C.encode_bytes_return(f"https://example.invalid/tap-example/token/{tid}.json".encode()))
    for tid in (0, 9):
        ch.revert(EXAMPLE, "netlistHashOf(uint256)", (tid,), B)
        ch.call(EXAMPLE, "imageHashOf(uint256)", (tid,), B, words(("bytes32", ZERO32)))
        ch.call(EXAMPLE, "netlistHashOf(uint256)", (tid,), B, words(("bytes32", ZERO32)))
        ch.revert(EXAMPLE, "entryIndexOf(uint256,uint256)", (tid, 0), B, "NotCovered")
        ch.revert(EXAMPLE, "entryIndexOf(uint256,uint256)", (tid, 1), B, "NotCovered")
    # a mint-bound collection (§8.2) holding the noManifest vector's token 1
    nm = V721["noManifest"]["valid"][0]["document"]["tap"]
    interfaces(ch, MINT_BOUND, {"ERC165", "ERC721", "ERC4906", "ITapNetlistNFT"}, B)
    ch.call(MINT_BOUND, "collection()", (), B, words(("address", MINT_BOUND)))
    ch.call(MINT_BOUND, "tokenRange()", (), B, words(("uint256", 1), ("uint256", 0)))
    ch.call(MINT_BOUND, "manifestHash()", (), B, words(("bytes32", ZERO32)))
    ch.call(MINT_BOUND, "masterSeed()", (), B, words(("bytes32", ZERO32)))
    ch.call(MINT_BOUND, "pools()", (), B, enc_pools([]))
    ch.call(MINT_BOUND, "frozen()", (), B, enc_bool(False))
    ch.call(MINT_BOUND, "netlistHashOf(uint256)", (1,), B, words(("bytes32", nm["netlist"]["sha256"])))
    ch.call(MINT_BOUND, "imageHashOf(uint256)", (1,), B, words(("bytes32", nm["image"]["sha256"])))
    # a plain ERC-721 at L0 without a manifest, whose tap.freeze probe uriFrozen() returns true
    interfaces(ch, L0_FREEZE, {"ERC165", "ERC721"}, B)
    ch.call(L0_FREEZE, "uriFrozen()", (), B, enc_bool(True))
    # a bridged copy (TAP-BR §5.3 mirror profile) holding the example's token 4
    t4 = next(t for t in ex["tokens"] if t["tokenId"] == 4)
    interfaces(ch, MIRROR, {"ERC165", "ERC721", "ERC4906", "ITapNetlistNFT", "ITapBridgeMirror"}, B)
    ch.call(MIRROR, "collection()", (), B, words(("address", MIRROR)))
    ch.call(MIRROR, "tokenRange()", (), B, words(("uint256", 1), ("uint256", 0)))
    ch.call(MIRROR, "manifestHash()", (), B, words(("bytes32", ex["manifestSha256"])))
    ch.call(MIRROR, "masterSeed()", (), B, words(("bytes32", ZERO32)))
    ch.call(MIRROR, "pools()", (), B, enc_pools([]))
    ch.call(MIRROR, "frozen()", (), B, enc_bool(False))
    ch.call(MIRROR, "netlistHashOf(uint256)", (4,), B, words(("bytes32", t4["netlistHash"])))
    ch.call(MIRROR, "imageHashOf(uint256)", (4,), B, words(("bytes32", t4["imageHash"])))
    return ch


# ---------------------------------------------------------------- chain 31337: the soulbound reference contract after the scenario

def chain_cred() -> Chain:
    ch = Chain(CRED_CHAIN)
    ch.notes.append("synthetic: the soulbound reference contract after the vectors' scenario (`final token states`, statuses at time 1900000000)")
    B = 1
    ch.put("eth_getBlockByNumber", ["latest", False], {"number": hex(B)})
    ch.put("eth_getCode", [CRED, hex(B)], "0xfe")
    interfaces(ch, CRED, {"ERC165", "ERC721", "ERC5192", "ITapCredential", "ITapCredentialProven", "ITapCredentialAttested", "ITapCredentialClaimed"}, B)
    final = next(s for s in VSB["scenario"] if s["step"] == "final token states")["result"]
    rebound = []
    for tid_s, st in sorted(final.items(), key=lambda kv: int(kv[0])):
        tid, c = int(tid_s), st["credential"]
        status = st["status"]["1900000000"]
        ch.call(CRED, "statusOf(uint256)", (tid,), B, enc_uint(STATUS_INDEX[status]))
        if st["holder"] is None:
            for sig in ("credentialOf(uint256)", "netlistHashOf(uint256)", "locked(uint256)", "ownerOf(uint256)"):
                ch.revert(CRED, sig, (tid,), B, "nonexistent token")
            continue
        ch.call(CRED, "credentialOf(uint256)", (tid,), B, words(
            ("uint8", c["kind"]), ("uint8", c["subject"]), ("address", c["issuer"]), ("bytes32", c["scope"]), ("bytes32", c["artifact"]),
            ("bytes32", c["evidence"]), ("uint64", c["issuedAt"]), ("uint64", c["expiresAt"]), ("uint256", c["replaces"])))
        ch.call(CRED, "netlistHashOf(uint256)", (tid,), B, words(("bytes32", c["artifact"])))
        ch.call(CRED, "locked(uint256)", (tid,), B, enc_bool(True))
        ch.call(CRED, "ownerOf(uint256)", (tid,), B, words(("address", st["holder"])))
        if c["replaces"]:
            rebound.append((c["replaces"], tid))
    topic = "0x" + P.keccak256(b"CredentialRebound(uint256,uint256)").hex()
    for old, new in rebound:
        log = {"address": CRED, "topics": [topic, "0x" + old.to_bytes(32, "big").hex(), "0x" + new.to_bytes(32, "big").hex()], "data": "0x",
               "blockNumber": hex(B), "logIndex": "0x0"}
        ch.put("eth_getLogs", [{"address": CRED, "topics": [topic, "0x" + old.to_bytes(32, "big").hex()], "fromBlock": "0x0", "toBlock": hex(B)}], [log])
    for name, sp in VSB["specs"].items():
        s = sp["spec"]
        ch.call(CRED, "specOf(bytes32)", (sp["specId"],), B, words(
            ("address", s["registrant"]), ("uint32", s["nIn"]), ("uint32", s["nOut"]), ("bytes32", s["target"]), ("uint32", s["maxGates"]),
            ("bool", s["unique"]), ("bytes32", s["series"]), ("uint64", s["commitStart"]), ("uint64", s["commitEnd"]), ("uint64", s["revealEnd"]),
            ("address", s["recoveryAuthority"]), ("bytes32", s["infoHash"]), ("uint256", VSB["bounds"]["maxGateWork"]), ("uint256", VSB["bounds"]["maxTableBytes"])))
    return ch


def build() -> dict:
    chains = [chain_56(), chain_196(), chain_cred()]
    disp = VCR["display"]
    return {
        "format": "tap-family-checker-fixture/1",
        "generator": "tools/family-checker/make_fixture.py",
        "sources": {
            "chain-reads.json": hashlib.sha256(open(os.path.join(P.CREDITS_DIR, "chain-reads.json"), "rb").read()).hexdigest(),
            "chain-snapshot.json": hashlib.sha256(open(os.path.join(P.TAPNFT_DIR, "chain-snapshot.json"), "rb").read()).hexdigest(),
            "credits vectors.json": hashlib.sha256(open(os.path.join(P.CREDITS_DIR, "vectors.json"), "rb").read()).hexdigest(),
            "tap-721 vectors.json": hashlib.sha256(open(os.path.join(P.TAPNFT_DIR, "vectors.json"), "rb").read()).hexdigest(),
            "soulbound vectors.json": hashlib.sha256(open(os.path.join(P.SOULBOUND_DIR, "vectors.json"), "rb").read()).hexdigest(),
        },
        "synthetic": {"196": [EXAMPLE, MINT_BOUND, L0_FREEZE, MIRROR], str(CRED_CHAIN): [CRED]},
        "chains": {str(c.id): {"notes": c.notes, "requests": dict(sorted(c.req.items()))} for c in chains},
        "publicationReads": publication_reads(),
        "erc1271": {"calls": disp["recorded"], "verificationBlocks": disp["verificationBlocks"]},
        "containers": disp["containers"],
    }


def main(argv) -> int:
    data = (json.dumps(build(), indent=1, sort_keys=False, ensure_ascii=False) + "\n").encode("utf-8")
    if argv[:1] == ["--check"]:
        try:
            cur = open(OUT, "rb").read()
        except FileNotFoundError:
            cur = b""
        if cur != data:
            print("fixtures/recorded-rpc.json is out of date: run make_fixture.py")
            return 1
        print("fixtures/recorded-rpc.json up to date")
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "wb") as f:
        f.write(data)
    print(f"wrote {OUT} ({len(data)} bytes, sha256 {hashlib.sha256(data).hexdigest()})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
